from pathlib import Path
from types import SimpleNamespace
from gui_smoke import Desktop

desktop = Desktop(SimpleNamespace(binary=Path("tools/installer/target/debug/hibi"), artifacts=Path("/tmp/hibi-gui-smoke"), display=__import__("os").environ["DISPLAY"], tesseract="/usr/bin/tesseract"))
try:
    desktop.launch()
    if sum(desktop.capture().getpixel((0,0))) < 300:
        desktop.click_theme()
    desktop.expect_theme("light")
    desktop.click_text("Claude Code")
    desktop.expect_components()

    desktop.manage_individual_settings()
    desktop.back_to_home()
    desktop.click_text("Codex CLI")
    desktop.expect_components()
    sidebar = " ".join(w["text"] for w in desktop.words() if w["x"] < 210)
    assert all(name in sidebar for name in ["Skills", "Config", "MCP"]), sidebar
    assert all(name not in sidebar for name in ["Agents", "Commands", "Plugins"]), sidebar
    desktop.passed("12-codex-three-categories")
    desktop.back_to_home()
    desktop.click_text("Manage sources")
    desktop.expect("Bundled library")
    desktop.inert("Remove source")
    desktop.inert("Edit source")
    desktop.passed("13-bundled-source-protected")
    desktop.key("a")
    desktop.expect("Where are your components")
    desktop.click_text("Git repository")
    desktop.expect("Connect a Git repository")
    desktop.key("Return")
    desktop.expect("Only HTTPS git URLs are allowed")
    desktop.passed("14-invalid-empty-git-url")
    desktop.click_text("Cancel")
    assert not (desktop.home / ".hibi/sources.yaml").exists()
    desktop.expect("Bundled library")
    desktop.key("a")
    desktop.expect("Where are your components")
    desktop.click_text("Local folder")
    desktop.expect("Choose a local folder")
    desktop.key("Return")
    desktop.expect("Local source path is empty")
    desktop.passed("15-empty-local-path")
    desktop.click_text("Cancel")
    desktop.expect("Bundled library")
    desktop.click_text("Back")
    desktop.expect("Your workspace")
    desktop.click_theme()
    desktop.expect_theme("dark")
    desktop.passed("16-dark-home-final")
    desktop.wait_for_appearance("dark")
    desktop.close_window()
    desktop.launch()
    desktop.expect_theme("dark")
    desktop.passed("17-dark-theme-restored")
    desktop.check_palette_restore()
    desktop.close_window()
    desktop.remove_source_with_busy_cache()
finally:
    desktop.close()
